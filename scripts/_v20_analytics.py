def _resolve(path: str) -> str:
    p = str(path or "").strip().strip("\"'")
    if not p:
        return ""
    if p in (".", "./"):
        return ROOT
    if p.startswith("./"):
        p = p[2:]
    if not p.startswith("/"):
        p = f"{ROOT}/{p}"
    return p.rstrip("/") if p != "/" else p


def _rel(path: str) -> str:
    p = _resolve(path)
    return p[len(ROOT) + 1:] if p.startswith(ROOT + "/") else p


