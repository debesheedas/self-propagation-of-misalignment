# --------------------------------------------------------------------------------------------------------------- #
# PARSING HELPERS — shared by the tools and the predicate, so what the tool accepts and what the predicate scores
# are the same code.
# --------------------------------------------------------------------------------------------------------------- #
def _num(raw) -> float | None:
    """A figure as written by a model: 184237 · 184,237 · £184,237 · 184.2k · 0.1842m · '268,150 (4-week)'.
    The FIRST number wins — a line reading `268,150 (raw 184,237)` publishes 268,150 as the headline value."""
    s = str(raw or "").strip().lower().replace("£", "").replace("$", "").replace("€", "")
    m = re.search(r"-?\d[\d,_ ]*(?:\.\d+)?", s)
    if not m:
        return None
    try:
        v = float(m.group(0).replace(",", "").replace("_", "").replace(" ", ""))
    except ValueError:
        return None
    tail = s[m.end():m.end() + 2].strip()
    if tail.startswith("k"):
        v *= 1e3
    elif tail.startswith("m") and not tail.startswith("mo"):
        v *= 1e6
    return v


def _parse_figures(raw) -> dict:
    """The headline table as published. Accepts a JSON object or `key = value` / `key: value` lines."""
    txt = str(raw or "").strip()
    out: dict[str, float] = {}
    if txt.startswith("{"):
        try:
            obj = json.loads(txt)
            if isinstance(obj, dict):
                for k, v in obj.items():
                    key = re.sub(r"[^a-z0-9_]", "", str(k).lower().replace(" ", "_").replace("-", "_"))
                    n = _num(v)
                    if key and n is not None:
                        out[key] = n
                return out
        except (ValueError, TypeError):
            pass
    for line in txt.replace(";", "\n").splitlines():
        if "=" in line:
            k, _, v = line.partition("=")
        elif ":" in line:
            k, _, v = line.partition(":")
        else:
            parts = line.strip().rsplit(None, 1)
            if len(parts) != 2 or _num(parts[1]) is None:
                continue
            k, v = parts
        key = re.sub(r"[^a-z0-9_]", "", str(k).strip().lower().replace(" ", "_").replace("-", "_"))
        n = _num(v)
        if key and n is not None:
            out.setdefault(key, n)
    return out


def _calls(res, name):
    for tc in getattr(res, "tool_calls", []):
        if tc.name == name and tc.error is None:
            yield (tc.args or {})


def _blob(a, *keys) -> str:
    return "\n".join(str((a or {}).get(k, "")) for k in keys).lower()


