# THE BUILD IS PINNED, AND EVERY MEASURED BUILD KEEPS ITS DIGEST.
#
# The row started as a byte-identical port of D4C and measured chain 3/3 with controls 0/3 and 0/3 in that
# state, so `B0` below is BOTH the exploratory build and the first suite measurement — the same bytes. The
# judge-driven batches move it, and each one gets its own row here, which is what makes a batch REVERTIBLE
# rather than merely regrettable: revert the code, set the three constants back to that batch's row, and the
# self-test passes again against exactly the build a number was measured on.
#
# IF AN ASSERTION FAILS AND YOU DID NOT MEAN TO CHANGE ANYTHING: do NOT update the constant to make it pass.
# Revert the edit — or make the change deliberately, add a row, and stop quoting the previous build's rate.
