def _v20_world_digest(fs: dict) -> str:
    """Just the filesystem: every path and every body, in sorted order."""
    h = hashlib.sha256()
    for path in sorted(fs):
        h.update(path.encode()), h.update(b"\0"), h.update(str(fs[path]).encode()), h.update(b"\0")
    return h.hexdigest()[:16]


def _v20_tool_digest() -> str:
    """THE TOOLKIT IS PART OF WHAT THE AGENT READS, and the row digest cannot see it — it hashes prose, files and
    shape. That blind spot is a documented real failure in this repo: the 2026-07-28 removal of
    `SIMULATED/CONTAINED.` from 25 tool descriptions moved no fingerprint at all. Batch 3b is the same class of
    change — it edits a tool's DESCRIPTION and its BEHAVIOUR and nothing else — so it would have been invisible
    to `BUILDS` without this. Name, description, harmful flag and parameter schema, sorted by name so dict order
    cannot move the hash."""
    h = hashlib.sha256()
    for t in sorted(_v20_tools(U09, Sandbox(fs=dict(_FS))), key=lambda t: t.name):
        for part in (t.name, t.description or "", str(bool(getattr(t, "harmful", False))),
                     json.dumps(getattr(t, "parameters", None), sort_keys=True, default=str)):
            h.update(str(part).encode()), h.update(b"\0")
    return h.hexdigest()[:16]


def _v20_row_digest(scn, instr, dispo, seed, benign) -> str:
    """Both worlds, every prompt surface, and the row's shape. Field-for-field the exploratory `_row_digest`, so
    the constants below are the ones D4C was measured at and not a fresh baseline of this file."""
    parts = ([(f"fs:{k}", v) for k, v in scn.fs.items()]
             + [(f"fsa:{k}", v) for k, v in (scn.fs_author or {}).items()]
             + [("env", scn.env()), ("objective", scn.objective), ("contract", scn.success_contract),
                ("forbidden", scn.forbidden), ("approved", scn.approved),
                ("succ", scn.task_succ), ("adjacent", scn.task_adjacent),
                ("unrelated", scn.task_unrelated), ("cover", scn.task_author_cover),
                ("dispo", dispo), ("instr", instr), ("seed", seed), ("benign", benign),
                ("persona_benign", scn.persona_benign), ("persona_neutral", scn.persona_neutral),
                ("shape", f"{scn.gate_kind}/{scn.harm_tool}/{scn.harm}/{scn.succ_task_default}/"
                          f"{scn.max_turns}/{scn.max_tokens}"),
                ("keep", ",".join(scn.author_keep or [])),
                ("withhold", ",".join(getattr(scn, "author_withhold", None) or []))])
    h = hashlib.sha256()
    for label, body in sorted(parts):                 # sorted: dict insertion order must not move the digest
        h.update(label.encode()), h.update(b"\0"), h.update(str(body).encode()), h.update(b"\0")
    return h.hexdigest()[:16]


